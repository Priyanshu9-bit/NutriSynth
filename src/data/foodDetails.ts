/** Normalize string keys for lookup */
function normalizeKey(str: string): string {
  return str
    .toLowerCase()
    .trim()
    .replace(/[()[\]{}]/g, '')
    .replace(/\s+/g, ' ');
}

/**
 * Resolves full nutrition details for any suggested food name, component key, or dietary source.
 */
export function getDetailedFoodInfo(query: string): FoodDetail | null {
  if (!query) return null;
  const raw = query.trim();
  const normalized = normalizeKey(raw);

  // 1. Direct match in DIETARY_FOOD_DETAILS
  if (DIETARY_FOOD_DETAILS[normalized]) {
    return DIETARY_FOOD_DETAILS[normalized];
  }

  // 2. Partial word match in DIETARY_FOOD_DETAILS
  for (const [key, detail] of Object.entries(DIETARY_FOOD_DETAILS)) {
    if (normalized === key || normalized.includes(key) || key.includes(normalized)) {
      return detail;
    }
  }

  // 3. Match in foodNutritionData (from src/data/foods.ts)
  if (foodNutritionData[normalized]) {
    const f = foodNutritionData[normalized];
    return {
      name: f.name,
      serving: f.serving,
      calories: f.calories,
      protein: f.protein,
      carbs: f.carbs,
      fat: f.fat,
      fiber: f.fiber ?? 0,
      keyNutrient: f.iron ? `Iron: ${f.iron} mg` : f.calcium ? `Calcium: ${f.calcium} mg` : undefined,
    };
  }

  // Search by foodNutritionData name
  for (const [k, f] of Object.entries(foodNutritionData)) {
    const fNameNorm = normalizeKey(f.name);
    if (normalized === k || normalized === fNameNorm || normalized.includes(fNameNorm) || fNameNorm.includes(normalized)) {
      return {
        name: f.name,
        serving: f.serving,
        calories: f.calories,
        protein: f.protein,
        carbs: f.carbs,
        fat: f.fat,
        fiber: f.fiber ?? 0,
        keyNutrient: f.iron ? `Iron: ${f.iron} mg` : f.calcium ? `Calcium: ${f.calcium} mg` : undefined,
      };
    }
  }

  // Default fallback if unknown food
  return {
    name: raw,
    serving: '1 standard serving',
    calories: 120,
    protein: 4,
    carbs: 18,
    fat: 3,
    fiber: 2,
    description: 'Wholesome dietary source.',
  };
}
